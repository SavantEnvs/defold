#!/usr/bin/env bash
#
# mayhem/build.sh — builds Defold's self-contained parsers (dlib json/image/zip/configfile, modelc
# glTF importer with its in-tree draco + meshoptimizer) with clang, the fuzz harnesses (libFuzzer and
# standalone), and the KAT probe used by mayhem/test.sh.
#
# Defold's own waf/CMake build needs a downloaded SDK; this builds only the parser sources, straight
# from the tree, air-gapped.
set -euo pipefail

[ -n "${SOURCE_DATE_EPOCH:-}" ] || unset SOURCE_DATE_EPOCH

: "${SANITIZER_FLAGS=-fsanitize=address,undefined -fno-sanitize-recover=all -fno-omit-frame-pointer}"
: "${DEBUG_FLAGS:=-g -gdwarf-3}"
: "${CC:=clang}" ; : "${CXX:=clang++}" ; : "${LIB_FUZZING_ENGINE:=-fsanitize=fuzzer}"
: "${MAYHEM_JOBS:=$(nproc)}"
: "${STANDALONE_FUZZ_MAIN:=/opt/mayhem/StandaloneFuzzTargetMain.c}"
: "${COVERAGE_FLAGS=}"
export SANITIZER_FLAGS DEBUG_FLAGS CC CXX LIB_FUZZING_ENGINE MAYHEM_JOBS COVERAGE_FLAGS

SRC="${SRC:-/mayhem}"
cd "$SRC"

B="$SRC/mayhem/build"
mkdir -p "$B/fuzz" "$B/plain" "$B/gen/draco"

DLIB="$SRC/engine/dlib/src"
MODELC="$SRC/engine/modelc/src"
DRACO="$SRC/external/draco/package/draco-1.5.7/src"
MESHOPT="$SRC/external/meshoptimizer/package/meshoptimizer-1.2/src"

# Draco's feature header is generated by Defold's CMake; reproduce it verbatim (decoder-only config).
printf '%s\n' '#ifndef DRACO_FEATURES_H_' '#define DRACO_FEATURES_H_' \
  '#define DRACO_MESH_COMPRESSION_SUPPORTED' '#define DRACO_NORMAL_ENCODING_SUPPORTED' \
  '#define DRACO_STANDARD_EDGEBREAKER_SUPPORTED' '#endif' > "$B/gen/draco/draco_features.h"

# Vectormath headers ship as a committed tarball; meshoptimizer is included as <meshoptimizer/meshoptimizer.h>.
mkdir -p "$B/gen/vm" "$B/gen/meshoptimizer"
tar xzf "$SRC/packages/vectormathlibrary-r1649-common.tar.gz" -C "$B/gen/vm"
cp -f "$MESHOPT/meshoptimizer.h" "$B/gen/meshoptimizer/meshoptimizer.h"

FONT="$SRC/engine/font/src"

INC="-I$FONT -I$FONT/render -I$SRC/engine/font -I$DLIB -I$MODELC -I$DRACO -I$B/gen -I$B/gen/vm/include -I$MESHOPT"
DEFS="-DZLIB_CONST -DMINIZ_NO_TIME -DZIP_ENABLE_INFLATE=1 -DZIP_ENABLE_DEFLATE=0 -DZIP_HAVE_SYMLINK=0 -DDLIB_LOG_DOMAIN=\"MODELC\""
FUZZ_CFLAGS="$SANITIZER_FLAGS -fsanitize=fuzzer-no-link $DEBUG_FLAGS -O1"
PLAIN_CFLAGS="-O2"

DLIB_SRCS="json utf8 hash dstrings array memory uri configfile configfile_http_null image zip zip_default
 log socket socket_posix socket_linux thread_posix mutex_posix condition_variable_posix sys sys_posix sys_linux
 time_posix spinlock_posix message path dlib stringpool dalloca file_descriptor file_descriptor_posix profile/profile_null"
MODEL_SRCS="modelimporter modelimporter_debug modelimporter_gltf modelimporter_compression"

# "<kind> <src> <obj>" jobs; kind selects compiler and std.
jobs="$B/jobs.txt"; : > "$jobs"
for f in $DLIB_SRCS; do
  [ "$f" = zip ] && continue
  echo "cxx17 $DLIB/dlib/$f.cpp dlib_$(echo "$f" | tr / _)" >> "$jobs"
done
echo "c11 $DLIB/zip/zip.c zip_c" >> "$jobs"
echo "cxx17 $DLIB/dlib/zip.cpp dlib_zip" >> "$jobs"
for f in $MODEL_SRCS; do
  std=cxx17; [ "$f" = modelimporter_compression ] && std=cxx11
  echo "$std $MODELC/$f.cpp model_$f" >> "$jobs"
done
for f in font font_ttf font_outline font_sdf util truetype/font_truetype truetype/font_colr; do
  echo "cxx17 $FONT/$f.cpp font_$(echo "$f" | tr / _)" >> "$jobs"
done
for f in $(grep -oE '[a-z_/]+\.cc$' "$SRC/external/draco/CMakeLists.txt"); do
  echo "cxx11 $DRACO/draco/$f draco_$(echo "$f" | tr / _)" >> "$jobs"
done
for f in "$MESHOPT"/*.cpp; do
  echo "cxx98 $f meshopt_$(basename "$f" .cpp)" >> "$jobs"
done

compile_one() {
  kind=$1; src=$2; name=$3; mode=$4
  case $kind in
    c11)   cc="$CC -std=gnu11" ;;
    cxx98) cc="$CXX -std=c++98" ;;
    cxx11) cc="$CXX -std=c++11" ;;
    *)     cc="$CXX -std=c++17" ;;
  esac
  # miniz's mz_zip_mem_read_func forms `pMem + file_ofs` before clamping the read to 0 bytes, so every
  # corrupt central-directory offset trips pointer-overflow without any out-of-bounds access; relax
  # only that one check, only for the zip library compile.
  extra=""; [ "$name" = zip_c ] && extra="-fno-sanitize=pointer-overflow"
  # draco is built with NDEBUG in Defold's own CMake (external/draco/CMakeLists.txt).
  case $name in draco_*) extra="$extra -DNDEBUG" ;; esac
  if [ "$mode" = plain ]; then
    # Oracle build: the project's normal flags, no sanitizer, no fuzzer instrumentation, no DWARF pin.
    # shellcheck disable=SC2086
    $cc -c $PLAIN_CFLAGS $COVERAGE_FLAGS $INC $DEFS -w "$src" -o "$B/plain/$name.o"
  else
    # shellcheck disable=SC2086
    $cc -c $FUZZ_CFLAGS $extra $INC $DEFS -w "$src" -o "$B/fuzz/$name.o"
  fi
}
export -f compile_one
export B INC DEFS FUZZ_CFLAGS PLAIN_CFLAGS COVERAGE_FLAGS
for mode in fuzz plain; do
  xargs -a "$jobs" -P "$MAYHEM_JOBS" -L1 bash -c 'compile_one "$0" "$1" "$2" '"$mode"
done

rm -f "$B/libdefold_parsers.a" "$B/libdefold_plain.a"
ar rcs "$B/libdefold_parsers.a" "$B"/fuzz/*.o
ar rcs "$B/libdefold_plain.a" "$B"/plain/*.o

# Harnesses: libFuzzer + standalone reproducer, both with lsan_off.
$CXX $SANITIZER_FLAGS $DEBUG_FLAGS -c "$SRC/mayhem/lsan_off.cc" -o "$B/lsan_off.o"
$CC $SANITIZER_FLAGS $DEBUG_FLAGS -c "$STANDALONE_FUZZ_MAIN" -o "$B/standalone_main.o"
for h in "$SRC"/mayhem/harnesses/fuzz_*.cpp; do
  n=$(basename "$h" .cpp)
  # shellcheck disable=SC2086
  $CXX -std=c++17 $SANITIZER_FLAGS $DEBUG_FLAGS -O1 -w $INC $DEFS -c "$h" -o "$B/$n.o"
  $CXX $SANITIZER_FLAGS $DEBUG_FLAGS $LIB_FUZZING_ENGINE "$B/$n.o" "$B/lsan_off.o" \
       "$B/libdefold_parsers.a" -lpthread -ldl -o "$SRC/$n"
  $CXX $SANITIZER_FLAGS $DEBUG_FLAGS "$B/standalone_main.o" "$B/$n.o" "$B/lsan_off.o" \
       "$B/libdefold_parsers.a" -lpthread -ldl -o "$SRC/$n-standalone"
done

# KAT probe for mayhem/test.sh: the same sources with normal flags, dynamically linked.
$CXX -std=c++17 -O2 $COVERAGE_FLAGS -w $INC $DEFS "$SRC/mayhem/kat/defold_kat.cpp" \
     "$B/libdefold_plain.a" -lpthread -ldl -o "$B/defold_kat"
